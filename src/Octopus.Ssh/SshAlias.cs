using System.Security.Cryptography;
using System.Text;

namespace Octopus.Ssh;

/// <summary>
/// Hosts whose alias ssh will not take on its command line. The app lets an alias be in any language (<c>Host 香港主服务器</c>),
/// but <c>ssh</c> checks the name it is given before it reads the configuration and stops with "hostname contains invalid
/// characters". For such an alias the app asks ssh for an ASCII name instead and hands it a generated configuration file in
/// which that name has the alias's own options, followed by the user's configuration for everything else.
/// </summary>
public static class SshAlias
{
    private const string Prefix = "octopus-";

    /// <summary>True for a host name that ssh reads as it is: letters, digits and <c>. _ - : @ [ ] %</c> in ASCII.</summary>
    public static bool IsPlain(string host) =>
        host.Length > 0 && host.All(c => c < 128 && (char.IsAsciiLetterOrDigit(c) || c is '.' or '_' or '-' or ':' or '@' or '[' or ']' or '%'));

    /// <summary>The ASCII name that stands for <paramref name="alias"/> on the command line.</summary>
    public static string WireName(string alias) =>
        Prefix + Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(alias.Trim().ToLowerInvariant())))[..10];

    /// <summary>
    /// The arguments of one ssh run (<c>[options] -- host [command]</c>) made runnable for an alias ssh does not take: the host
    /// becomes <see cref="WireName"/> and <c>-F</c> points at the generated file. Any other run is returned as it is, as is one
    /// whose alias has no block in the configuration (ssh then says what is wrong with it).
    /// </summary>
    public static IReadOnlyList<string> Prepare(IReadOnlyList<string> arguments) =>
        Prepare(arguments, SshHostCatalog.UserHome);

    internal static IReadOnlyList<string> Prepare(IReadOnlyList<string> arguments, string home)
    {
        var separator = arguments.ToList().IndexOf("--");
        if (separator < 0 || separator + 1 >= arguments.Count || IsPlain(arguments[separator + 1]))
        {
            return arguments;
        }
        var alias = arguments[separator + 1];
        if (EnsureFile(alias, home) is not { } file)
        {
            return arguments;
        }
        var result = new List<string>(arguments.Count + 2) { "-F", file };
        result.AddRange(arguments);
        result[separator + 3] = WireName(alias);
        return result;
    }

    /// <summary>Writes (when it changed) the file for <paramref name="alias"/> and returns its path; null when the alias has no block to copy.</summary>
    private static string? EnsureFile(string alias, string home)
    {
        var configPath = Path.Combine(home, ".ssh", "config");
        string text;
        try
        {
            text = File.ReadAllText(configPath);
        }
        catch (Exception e) when (e is IOException or UnauthorizedAccessException)
        {
            return null;
        }
        var body = BlockBody(text, alias);
        if (body is null)
        {
            return null;
        }
        var content = new StringBuilder()
            .AppendLine("# Generated by Octopus: ssh does not take a host name with these characters, so it is asked for this one.")
            .AppendLine("Host " + WireName(alias))
            .AppendLine(string.Join('\n', body))
            // What the user's file says for every host (Host *, Match, ...) still applies, after the alias's own options.
            .AppendLine("Match all")
            .AppendLine("Include \"" + configPath.Replace('\\', '/') + "\"")
            .ToString();
        try
        {
            var directory = Path.Combine(home, ".octopus", "ssh");
            Directory.CreateDirectory(directory);
            var path = Path.Combine(directory, WireName(alias) + ".conf");
            if (!File.Exists(path) || File.ReadAllText(path) != content)
            {
                File.WriteAllText(path, content, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
            }
            return path;
        }
        catch (Exception e) when (e is IOException or UnauthorizedAccessException)
        {
            return null;
        }
    }

    /// <summary>The option lines under the first <c>Host</c> line that names <paramref name="alias"/>, or null when there is none.</summary>
    internal static IReadOnlyList<string>? BlockBody(string config, string alias)
    {
        List<string>? body = null;
        foreach (var raw in config.Split('\n'))
        {
            var line = raw.Trim();
            if (line.Length == 0 || line[0] == '#')
            {
                continue;
            }
            var (keyword, args) = SshConfigParser.SplitLine(line);
            var isHeader = keyword.Equals("host", StringComparison.OrdinalIgnoreCase) || keyword.Equals("match", StringComparison.OrdinalIgnoreCase);
            if (body is not null)
            {
                if (isHeader)
                {
                    break;
                }
                body.Add(line);
            }
            else if (keyword.Equals("host", StringComparison.OrdinalIgnoreCase) && args.Any(a => a.Equals(alias, StringComparison.OrdinalIgnoreCase)))
            {
                body = [];
            }
        }
        return body;
    }
}
