using System.Buffers;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace Octopus.Agents.Signals;

/// <summary>One hook handler to generate: the agent's event name and the command line it runs.</summary>
internal sealed record GeneratedHook(string Event, string Command);

/// <summary>
/// The text of everything the planner generates. Pure: no IO, so each format can be checked in tests. None of it
/// holds a secret; the token reaches the forwarder only through the agent's environment.
/// </summary>
internal static class SignalAttachContent
{
    public const string PluginName = "octopus-signal";
    private const string PluginDescription =
        "Forwards this session's events to Octopus. Generated by Octopus for sessions it starts; not installed anywhere.";

    private static readonly JsonWriterOptions Indented = new() { Indented = true, Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };
    private static readonly JsonWriterOptions Compact = new() { Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };

    /// <summary>
    /// A command line for a slot the agent runs through a shell. Arguments that need it are quoted: POSIX single
    /// quotes on macOS and Linux (and for Claude Code on Windows, which runs hooks with Git Bash), double quotes on
    /// Windows otherwise.
    /// </summary>
    public static string CommandLine(string executable, IEnumerable<string> arguments, bool windows) =>
        string.Join(' ', new[] { executable }.Concat(arguments).Select(a => Quote(a, windows)));

    internal static string Quote(string value, bool windows)
    {
        if (value.Length > 0 && value.All(c => char.IsAsciiLetterOrDigit(c) || "-_./:=@%+,".Contains(c) || (windows && c == '\\')))
        {
            return value;
        }
        return windows
            ? "\"" + value.Replace("\"", "\\\"", StringComparison.Ordinal) + "\""
            : "'" + value.Replace("'", "'\\''", StringComparison.Ordinal) + "'";
    }

    /// <summary>
    /// Claude Code settings with nothing but <c>statusLine</c>. Passed with <c>--settings</c>, it replaces the user's
    /// status line for this session only, which is why the user's command is chained; the user's padding and vim
    /// indicator choice are kept so their status line looks the same.
    /// </summary>
    public static string ClaudeSettings(string command, int? refreshInterval, UserSlotCommand? user)
    {
        return Write(Indented, writer =>
        {
            writer.WriteStartObject();
            writer.WriteStartObject("statusLine");
            writer.WriteString("type", "command");
            writer.WriteString("command", command);
            if (refreshInterval is > 0)
            {
                writer.WriteNumber("refreshInterval", refreshInterval.Value);
            }
            if (user?.Padding is { } padding)
            {
                writer.WriteNumber("padding", padding);
            }
            if (user?.HideVimModeIndicator is { } hide)
            {
                writer.WriteBoolean("hideVimModeIndicator", hide);
            }
            writer.WriteEndObject();
            writer.WriteEndObject();
        });
    }

    /// <summary><c>plugin.json</c> for both <c>.claude-plugin/</c> and <c>.cursor-plugin/</c>.</summary>
    public static string PluginManifest() => Write(Indented, writer =>
    {
        writer.WriteStartObject();
        writer.WriteString("name", PluginName);
        writer.WriteString("version", "1.0.0");
        writer.WriteString("description", PluginDescription);
        writer.WriteEndObject();
    });

    /// <summary>Claude Code's plugin <c>hooks/hooks.json</c>: event → matcher groups → command handlers.</summary>
    public static string ClaudeHooks(IReadOnlyList<GeneratedHook> hooks, int timeoutSeconds) => Write(Indented, writer =>
    {
        writer.WriteStartObject();
        writer.WriteString("description", PluginDescription);
        writer.WritePropertyName("hooks");
        WriteMatcherGroups(writer, hooks, timeoutSeconds);
        writer.WriteEndObject();
    });

    /// <summary>Cursor's own hooks format (<c>{"version":1,"hooks":{"stop":[{"command":…}]}}</c>).</summary>
    public static string CursorHooks(IReadOnlyList<GeneratedHook> hooks, int timeoutSeconds) => Write(Indented, writer =>
    {
        writer.WriteStartObject();
        writer.WriteNumber("version", 1);
        writer.WriteStartObject("hooks");
        foreach (var group in hooks.GroupBy(h => h.Event, StringComparer.Ordinal))
        {
            writer.WriteStartArray(group.Key);
            foreach (var hook in group)
            {
                writer.WriteStartObject();
                writer.WriteString("command", hook.Command);
                writer.WriteNumber("timeout", timeoutSeconds);
                writer.WriteEndObject();
            }
            writer.WriteEndArray();
        }
        writer.WriteEndObject();
        writer.WriteEndObject();
    });

    /// <summary>
    /// A Grok config overlay for <c>GROK_CONFIG</c>, which Grok reads as an inline JSON object (its guide,
    /// 05-configuration.md). The shape mirrors the TOML: <c>ui.status_line</c> and <c>hooks.&lt;Event&gt;</c> matcher groups.
    /// </summary>
    public static string GrokOverlay(string? statusLineCommand, int? refreshInterval, int? padding, IReadOnlyList<GeneratedHook> hooks, int timeoutSeconds) =>
        Write(Compact, writer =>
        {
            writer.WriteStartObject();
            if (statusLineCommand is not null)
            {
                writer.WriteStartObject("ui");
                writer.WriteStartObject("status_line");
                writer.WriteString("type", "command");
                writer.WriteString("command", statusLineCommand);
                if (refreshInterval is > 0)
                {
                    writer.WriteNumber("refresh_interval", refreshInterval.Value);
                }
                if (padding is { } p)
                {
                    writer.WriteNumber("padding", p);
                }
                writer.WriteEndObject();
                writer.WriteEndObject();
            }
            if (hooks.Count > 0)
            {
                writer.WritePropertyName("hooks");
                WriteMatcherGroups(writer, hooks, timeoutSeconds);
            }
            writer.WriteEndObject();
        });

    /// <summary>Config content for <c>OPENCODE_CONFIG_CONTENT</c> that loads the generated plugin file.</summary>
    public static string OpenCodeConfig(string pluginFileUrl) => Write(Compact, writer =>
    {
        writer.WriteStartObject();
        writer.WriteStartArray("plugin");
        writer.WriteStringValue(pluginFileUrl);
        writer.WriteEndArray();
        writer.WriteEndObject();
    });

    /// <summary>
    /// The JS forwarder for OpenCode, whose extensions are in-process plugins rather than commands. It writes the
    /// same envelope as <c>octopus-signal</c> (design/plugins/13-P0验证记录.md §2) to the endpoint in the environment.
    /// <paramref name="channels"/> maps an event key to a channel; the key is the event type, or for an event whose
    /// <c>properties.status.type</c> is a string also <c>type:status</c> (e.g. <c>session.status:busy</c>).
    /// </summary>
    public static string OpenCodePlugin(string agentId, IReadOnlyDictionary<string, string> channels)
    {
        var map = Write(Compact, writer =>
        {
            writer.WriteStartObject();
            foreach (var (key, channel) in channels.OrderBy(c => c.Key, StringComparer.Ordinal))
            {
                writer.WriteString(key, channel);
            }
            writer.WriteEndObject();
        });
        var agent = Write(Compact, writer => writer.WriteStringValue(agentId));
        return OpenCodePluginTemplate
            .Replace("__AGENT__", agent, StringComparison.Ordinal)
            .Replace("__CHANNELS__", map, StringComparison.Ordinal);
    }

    private const string OpenCodePluginTemplate =
        """
        // Octopus signal forwarder for OpenCode. Generated by Octopus; rewritten whenever it changes, do not edit.
        //
        // OpenCode loads it through OPENCODE_CONFIG_CONTENT for sessions Octopus starts, and nowhere else. For each
        // event listed in CHANNELS it sends one envelope to Octopus, the same format the octopus-signal executable
        // writes: a single UTF-8 JSON object per connection { v, token, item, agent, channel, account, ts, payload },
        // with the event as the payload string. Endpoint and token come from the environment Octopus gave this
        // session. Every failure is silent: Octopus being closed must never disturb OpenCode.
        import net from "node:net";

        const AGENT = __AGENT__;
        const CHANNELS = __CHANNELS__;
        const REPEAT_WINDOW_MS = 2000; // the same payload on the same channel is not sent twice within this window
        const SEND_TIMEOUT_MS = 500;
        const lastSent = new Map();

        function send(channel, payload) {
          const endpoint = process.env.OCTOPUS_SIGNAL_ENDPOINT;
          if (!endpoint) return;
          const now = Date.now();
          const previous = lastSent.get(channel);
          if (previous && previous.payload === payload && now - previous.at < REPEAT_WINDOW_MS) return;
          lastSent.set(channel, { payload, at: now });
          const accountVar = process.env.OCTOPUS_SIGNAL_ACCOUNT_VAR;
          const envelope = JSON.stringify({
            v: 1,
            token: process.env.OCTOPUS_SIGNAL_TOKEN ?? "",
            item: process.env.OCTOPUS_ITEM_ID ?? "",
            agent: AGENT,
            channel,
            account: accountVar ? (process.env[accountVar] ?? "") : "",
            ts: now,
            payload,
          });
          try {
            // A Unix socket path or a Windows named pipe (\\.\pipe\name): node:net takes both as `path`.
            const socket = net.createConnection({ path: endpoint });
            socket.setTimeout(SEND_TIMEOUT_MS, () => socket.destroy());
            socket.on("error", () => {});
            socket.end(envelope);
          } catch {
            // Nobody listening.
          }
        }

        export const OctopusSignal = async () => ({
          event: async ({ event }) => {
            if (!event || typeof event.type !== "string") return;
            const keys = [event.type];
            const status = event.properties?.status?.type;
            if (typeof status === "string") keys.push(`${event.type}:${status}`);
            for (const key of keys) {
              const channel = CHANNELS[key];
              if (channel) send(channel, JSON.stringify(event));
            }
          },
        });

        """;

    /// <summary>A TOML inline array of basic strings, for <c>-c notify=[…]</c>.</summary>
    public static string TomlArray(IEnumerable<string> items)
    {
        var sb = new StringBuilder("[");
        var first = true;
        foreach (var item in items)
        {
            if (!first)
            {
                sb.Append(',');
            }
            first = false;
            sb.Append('"');
            foreach (var c in item)
            {
                switch (c)
                {
                    case '"': sb.Append("\\\""); break;
                    case '\\': sb.Append("\\\\"); break;
                    case '\n': sb.Append("\\n"); break;
                    case '\r': sb.Append("\\r"); break;
                    case '\t': sb.Append("\\t"); break;
                    default:
                        if (char.IsControl(c))
                        {
                            sb.Append("\\u").Append(((int)c).ToString("X4", System.Globalization.CultureInfo.InvariantCulture));
                        }
                        else
                        {
                            sb.Append(c);
                        }
                        break;
                }
            }
            sb.Append('"');
        }
        return sb.Append(']').ToString();
    }

    /// <summary>
    /// Merges our overlay into one the user already sets in the same variable, so theirs keeps working: objects merge
    /// key by key, arrays are concatenated (plugins, hook groups), other values are ours. Null when the user's value
    /// is not a JSON object; the caller then leaves the variable alone.
    /// </summary>
    public static string? MergeJsonObjects(string existing, string ours)
    {
        try
        {
            var options = new JsonDocumentOptions { CommentHandling = JsonCommentHandling.Skip, AllowTrailingCommas = true };
            if (JsonNode.Parse(existing, documentOptions: options) is not JsonObject target
                || JsonNode.Parse(ours) is not JsonObject source)
            {
                return null;
            }
            Merge(target, source);
            return Write(Compact, writer => target.WriteTo(writer));
        }
        catch (JsonException)
        {
            return null;
        }
    }

    private static void Merge(JsonObject target, JsonObject source)
    {
        foreach (var (key, value) in source.ToList())
        {
            source.Remove(key);
            if (target[key] is JsonObject into && value is JsonObject from)
            {
                Merge(into, from);
            }
            else if (target[key] is JsonArray list && value is JsonArray more)
            {
                foreach (var item in more.ToList())
                {
                    more.Remove(item);
                    list.Add(item);
                }
            }
            else
            {
                target[key] = value;
            }
        }
    }

    private static void WriteMatcherGroups(Utf8JsonWriter writer, IReadOnlyList<GeneratedHook> hooks, int timeoutSeconds)
    {
        writer.WriteStartObject();
        foreach (var group in hooks.GroupBy(h => h.Event, StringComparer.Ordinal))
        {
            writer.WriteStartArray(group.Key);
            writer.WriteStartObject();
            writer.WriteStartArray("hooks");
            foreach (var hook in group)
            {
                writer.WriteStartObject();
                writer.WriteString("type", "command");
                writer.WriteString("command", hook.Command);
                writer.WriteNumber("timeout", timeoutSeconds);
                writer.WriteEndObject();
            }
            writer.WriteEndArray();
            writer.WriteEndObject();
            writer.WriteEndArray();
        }
        writer.WriteEndObject();
    }

    private static string Write(JsonWriterOptions options, Action<Utf8JsonWriter> write)
    {
        var buffer = new ArrayBufferWriter<byte>();
        using (var writer = new Utf8JsonWriter(buffer, options))
        {
            write(writer);
        }
        return Encoding.UTF8.GetString(buffer.WrittenSpan);
    }
}
